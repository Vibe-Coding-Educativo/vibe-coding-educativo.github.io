function setLanguage(lang) {
  if (!translations[lang]) return;
  document.documentElement.lang = lang;
  const langStrings = translations[lang];
  document.querySelectorAll('[data-lang]').forEach((el) => {
    const key = el.dataset.lang;
    if (langStrings[key]) {
      if (key === 'whatIsContent') {
        // Conservar el contenedor y sus clases (incl. variantes dark)
        el.innerHTML = langStrings[key];
      } else {
        el.innerHTML = langStrings[key];
      }
    }
  });
  // Enlaces e imágenes que existen en cada idioma, como la guía «Vibe coding responsable»
  document.querySelectorAll('[data-href-lang]').forEach((el) => {
    el.href = el.dataset.hrefLang.replace('{lang}', lang);
  });
  document.querySelectorAll('[data-src-lang]').forEach((el) => {
    el.src = el.dataset.srcLang.replace('{lang}', lang);
  });
  localStorage.setItem('vibeLang', lang);
}

function getInitialLanguage() {
  const savedLang = localStorage.getItem('vibeLang');
  if (savedLang && translations[savedLang]) {
    return savedLang;
  }
  const browserLang = navigator.language.split('-')[0];
  return translations[browserLang] ? browserLang : 'es';
}

document.addEventListener('DOMContentLoaded', () => {
  const mobileMenuButton = document.getElementById('mobile-menu-button');
  const mobileMenu = document.getElementById('mobile-menu');
  const langSelector = document.getElementById('lang-selector');
  // Controles de tema eliminados: solo se respeta el modo del sistema

  if (mobileMenuButton && mobileMenu) {
    mobileMenuButton.addEventListener('click', () => {
      mobileMenu.classList.toggle('hidden');
    });

    const navLinks = document.querySelectorAll('#mobile-menu a, #main-nav a');
    navLinks.forEach((link) => {
      link.addEventListener('click', () => {
        mobileMenu.classList.add('hidden');
      });
    });
  }

  const initialLang = getInitialLanguage();
  if (langSelector) langSelector.value = initialLang;
  setLanguage(initialLang);

  if (langSelector) {
    langSelector.addEventListener('change', (e) => {
      setLanguage(e.target.value);
    });
  }

  const agentOpenButton = document.getElementById('agent-open-button');
  if (agentOpenButton) {
    agentOpenButton.addEventListener('click', (event) => {
      event.preventDefault();
      const popupWidth = 960;
      const popupHeight = 720;
      const dualScreenLeft = window.screenLeft ?? window.screenX ?? 0;
      const dualScreenTop = window.screenTop ?? window.screenY ?? 0;
      const viewportWidth =
        window.innerWidth || document.documentElement.clientWidth || screen.width;
      const viewportHeight =
        window.innerHeight || document.documentElement.clientHeight || screen.height;
      const left = Math.max(0, dualScreenLeft + (viewportWidth - popupWidth) / 2);
      const top = Math.max(0, dualScreenTop + (viewportHeight - popupHeight) / 2);
      const agentUrl = agentOpenButton.getAttribute('href');
      const features = [
        'noopener=yes',
        'noreferrer=yes',
        `width=${popupWidth}`,
        `height=${popupHeight}`,
        `left=${Math.round(left)}`,
        `top=${Math.round(top)}`,
        'resizable=yes',
        'scrollbars=yes',
        'toolbar=no',
        'location=no',
        'status=no',
        'menubar=no',
      ].join(',');
      const agentWindow = window.open(agentUrl, 'vibeAgentWindow', features);
      if (agentWindow) {
        agentWindow.focus();
        return;
      }

      console.warn('Autoriza las ventanas emergentes para abrir el agente.');
    });
  }

  // Sin lógica de tema manual
});
